# brain/skills/llm/_whitelist.py
# Whitelist команд для LLM.
#
# LLM может вернуть type=command только с командой из этого списка.
# Если команда не в списке — unknown → «Не понял».
#
# A2/B1 (день 29): убран "громкость " из COMMAND_PREFIXES.
#   Раньше: LLM возвращал «громкость сорок пять» как command, router не
#   понимал (parse_volume None), LLM снова → зацикливание. Теперь:
#   LLM не может вернуть «громкость X» как command. Валидную «громкость 50»
#   ловит controls.parse_volume ДО LLM. Невалидную — NOT_UNDERSTOOD.
#
# B-новое (день 30): _MUSIC_NOISE_OBJECTS — «включи что-нибудь»,
#   «поставь эдакое», «найди чего-нибудь». Раньше: prefix «включи »
#   проходил, LLM возвращал command, classify → play_track с мусором,
#   Яндекс возвращал что попало. Теперь: prefix + пустой объект ИЛИ
#   объект из _MUSIC_NOISE_OBJECTS → False.
#
# FIX: убран NON_MUSIC_OBJECTS. Он блокировал реальные музыкальные команды
# («включи лампу» → группа «Лампа», «включи машину времени» → «Машина времени»,
# «включи свету» → певица «Света»). Для домашнего проекта, где нет умного дома,
# чёрный список объектов — решение проблемы, которой нет.
# Если music не найдёт артиста — он сам скажет «не нашёл», это нормально.

import re


# ==================== РАЗРЕШЁННЫЕ КОМАНДЫ ====================

EXACT_COMMANDS = {
    # Музыка — управление
    "пауза", "продолжи", "продолжить", "стоп", "дальше", "назад",
    "следующий", "предыдущий", "пропусти",
    "громче", "тише", "погромче", "потише",
    "что играет", "что за песня", "что за трек", "что сейчас",

    # Smalltalk
    "привет", "спасибо", "кто ты", "как дела", "как ты",
    "что ты умеешь", "помощь",

    # Система
    "статус", "статус системы", "как система",

    # Погода
    "погода", "какая погода", "погода сегодня",

    # Очистка
    "почисти диск", "почисти диск c", "очисти диск", "очисти диск c",
}


# Префиксы (lowercase)
# A2/B1: убран "громкость " — LLM не возвращает «громкость X» как command.
COMMAND_PREFIXES = [
    "поставь ",
    "напомни ",
    "запомни ",
    "когда ",
    "найди ",
    "продолжи ",
    "включи ",
    "включить ",
    "играй ",
]


# ==================== ЗАПРЕЩЁННЫЕ КОМАНДЫ ====================

FORBIDDEN = [
    "формат", "форматировать", "удали всё", "удали все",
    "удали диск", "удали c:", "удали d:",
    "shutdown", "reboot", "перезагрузи", "выключи компьютер",
    "rm -rf", "del /f", "format c:",
    "удали систему", "удали windows", "удали папку windows",
]


# ==================== МУСОРНЫЕ ОБЪЕКТЫ ====================
# B-новое: если после prefix стоит «что-нибудь», «эдакое» — это не команда,
# это «включи что-нибудь». LLM не должна превращать это в play_track.
_MUSIC_NOISE_OBJECTS = {
    "что-нибудь", "что нибудь",
    "чего-нибудь", "чего нибудь",
    "эдакое", "этакое",
    "нормального", "нормальное",
    "любого", "любое",
    "какое-нибудь", "какое нибудь",
    "какую-нибудь", "какую нибудь",
}


# ==================== ПРОВЕРКА ====================

def is_command_allowed(text: str) -> bool:
    """Проверить, разрешена ли команда."""
    if not text:
        return False

    tl = text.lower().strip()

    for bad in FORBIDDEN:
        if bad in tl:
            return False

    if tl in EXACT_COMMANDS:
        return True

    for prefix in COMMAND_PREFIXES:
        if tl.startswith(prefix):
            rest = tl[len(prefix):].strip()
            # «включи » без объекта — не команда
            if not rest:
                return False
            # «включи что-нибудь» / «поставь эдакое» — не команда
            if rest in _MUSIC_NOISE_OBJECTS:
                return False
            return True

    return False


def is_forbidden(text: str) -> bool:
    """Проверить, содержит ли текст запрещённое."""
    if not text:
        return False
    tl = text.lower().strip()
    for bad in FORBIDDEN:
        if bad in tl:
            return True
    return False