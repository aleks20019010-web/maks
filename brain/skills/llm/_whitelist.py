# brain/skills/llm/_whitelist.py
# Whitelist команд для LLM.
#
# LLM может вернуть type=command только с командой из этого списка.
# Если команда не в списке — unknown → «Не понял, сэр».
#
# Безопасность: LLM не должна возвращать «формат диск», «удали всё» и т.д.
# Только безопасные команды: музыка, погода, статус, напоминания, cleanup, smalltalk.
#
# FIX: «включи X» — если X содержит не-музыкальный объект (свет, дверь, ...) — False.
# Иначе — True (музыка, ария, рок, фильм, ...).

import re


# ==================== РАЗРЕШЁННЫЕ КОМАНДЫ ====================

EXACT_COMMANDS = {
    # Музыка — управление
    "пауза", "продолжи", "продолжить", "стоп", "дальше", "назад",
    "следующий", "предыдущий", "пропусти",
    "громче", "тише", "погромче", "потише",
    "что играет", "что за песня", "что за трек", "что сейчас",

    # Smalltalk
    "привет", "спасибо", "кто ты", "как дела", "как ты",
    "что ты умеешь", "помощь",

    # Система
    "статус", "статус системы", "как система",

    # Погода
    "погода", "какая погода", "погода сегодня",

    # Очистка
    "почисти диск", "почисти диск c", "очисти диск", "очисти диск c",
}


# Не-музыкальные объекты — если «включи X» содержит их, команда запрещена
NON_MUSIC_OBJECTS = {
    "свет", "дверь", "окно", "компьютер", "телевизор", "кондиционер",
    "обогреватель", "чайник", "кофеварка", "микроволновка", "плита",
    "вентилятор", "лампа", "лампочка", "люстра", "бра",
    "холодильник", "стиральная", "посудомоечная", "пылесос",
    "машина", "автомобиль", "гараж", "ворота", "замок",
    "сигнализация", "камера", "робот",
}


# Префиксы (lowercase)
COMMAND_PREFIXES = [
    "поставь ",
    "напомни ",
    "запомни ",
    "когда ",
    "громкость ",
    "найди ",
    "продолжи ",
]


# ==================== ЗАПРЕЩЁННЫЕ КОМАНДЫ ====================

FORBIDDEN = [
    "формат", "форматировать", "удали всё", "удали все",
    "удали диск", "удали c:", "удали d:",
    "shutdown", "reboot", "перезагрузи", "выключи компьютер",
    "rm -rf", "del /f", "format c:",
    "удали систему", "удали windows", "удали папку windows",
]


# ==================== ПРОВЕРКА ====================

def is_command_allowed(text: str) -> bool:
    """Проверить, разрешена ли команда."""
    if not text:
        return False

    tl = text.lower().strip()

    for bad in FORBIDDEN:
        if bad in tl:
            return False

    if tl in EXACT_COMMANDS:
        return True

    for prefix in ("включи ", "включить ", "играй "):
        if tl.startswith(prefix):
            rest = tl[len(prefix):].strip()
            if any(obj in rest for obj in NON_MUSIC_OBJECTS):
                return False
            return True

    for prefix in COMMAND_PREFIXES:
        if tl.startswith(prefix):
            return True

    return False


def is_forbidden(text: str) -> bool:
    """Проверить, содержит ли текст запрещённое."""
    if not text:
        return False
    tl = text.lower().strip()
    for bad in FORBIDDEN:
        if bad in tl:
            return True
    return False