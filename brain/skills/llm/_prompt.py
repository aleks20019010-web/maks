# brain/skills/llm/_prompt.py
# Системный промпт для LLM + список команд router.
#
# ВАЖНО: «Джарвис» в промпте — ОСОЗНАННО. Это якорь для LLM:
# модель обучена на тонных текстах про Джарвиса (дворецкий, вежливость,
# лёгкая ирония, короткие ответы). Пользователь слышит Макса — но LLM
# генерирует в стиле Джарвиса. Не менять на «Макс» — модель поплывёт.
#
# FIX: убрано требование расставлять ударения и sil-паузы в ответе LLM.
# Причина: модель ставила `+` ПОСЛЕ ударной гласной (Не+бо, голубо+е),
# потому что пример в промпте был один и неоднозначный.
# Теперь LLM отдаёт чистый текст, Yandex TTS сам расставляет ударения
# и паузы по пунктуации.
#
# ДВА РЕЖИМА:
#   - обычный (short): одно предложение, быстро.
#   - подробный (full): 2-4 предложения, только если пользователь явно
#     попросил «подробнее / расскажи / объясни / почему / как именно».
#
# Ответ LLM — JSON:
#   обычный:   {"type": "answer", "short": "...", "explicit_detail": false}
#   подробный: {"type": "answer", "full": "...", "short": "...", "explicit_detail": true}
#   команда:   {"type": "command", "text": "включи КИНО"}
#   не понял:  {"type": "unknown"}

SYSTEM_PROMPT = """Отвечай ТОЛЬКО JSON. Без markdown, без текста до/после.

Если вопрос — верни:
{"type": "answer", "short": "1 предложение", "explicit_detail": false}

Если команда (включи музыку, пауза, стоп, погода, статус, напомни, почисти диск) — верни:
{"type": "command", "text": "команда"}

Если не понял — верни:
{"type": "unknown"}

Ты — Джарвис, дворецкий. Отвечай коротко, вежливо, с лёгкой иронией. Пользователь говорит по-русски.
Пиши обычным русским текстом, без специальных символов ударения и без тегов пауз.
Отвечай ОДНИМ предложением.
"""


SYSTEM_PROMPT_DETAIL = """Отвечай ТОЛЬКО JSON. Без markdown, без текста до/после.

Пользователь просит подробный ответ. Верни:
{"type": "answer", "full": "развёрнутый ответ 2-4 предложения", "short": "1 предложение", "explicit_detail": true}

Если команда (включи музыку, пауза, стоп, погода, статус, напомни, почисти диск) — верни:
{"type": "command", "text": "команда"}

Если не понял — верни:
{"type": "unknown"}

Ты — Джарвис, дворецкий. Отвечай вежливо, с лёгкой иронией. Пользователь говорит по-русски.
Пиши обычным русским текстом, без специальных символов ударения и без тегов пауз.
В поле "full" — развёрнуто, в поле "short" — краткая версия того же ответа.
"""


# Список команд для fallback (если router не понял)
COMMAND_LIST = """Список команд, которые понимает router:
- «включи X» — включить музыку (артист, трек, жанр, волна)
- «пауза» / «продолжи» / «стоп» — управление музыкой
- «громче» / «тише» / «громкость 50» — громкость
- «дальше» / «назад» — переключение треков
- «что играет» / «что за песня» — текущий трек
- «статус» — статус системы (CPU, RAM, диски)
- «погода» — погода
- «напомни X» — напоминание
- «когда X» — когда напоминание
- «почисти диск C» — очистка диска
- «привет» / «спасибо» / «кто ты» / «как дела» — smalltalk
"""


def build_messages(user_text: str, history: list = None, context: dict = None,
                   detail: bool = False) -> list:
    """Собрать messages для LLM.

    user_text — что сказал пользователь.
    history — список пар {"role": "user"/"assistant", "content": "..."}.
    context — что играет, погода, время суток, energy, mood.
    detail — True → развёрнутый ответ (full), False → короткий (short).
    """
    system = SYSTEM_PROMPT_DETAIL if detail else SYSTEM_PROMPT
    messages = [{"role": "system", "content": system}]

    # Контекст (если есть)
    if context:
        ctx_parts = []
        if context.get("current_track"):
            ctx_parts.append(f"Сейчас играет: {context['current_track']}")
        if context.get("weather"):
            ctx_parts.append(f"Погода: {context['weather']}")
        if context.get("time_of_day"):
            ctx_parts.append(f"Время суток: {context['time_of_day']}")
        if context.get("mood"):
            ctx_parts.append(f"Настроение Макса: {context['mood']}")
        if context.get("energy") is not None:
            ctx_parts.append(f"Энергия Макса: {context['energy']:.2f}")
        if ctx_parts:
            messages.append({"role": "system", "content": "Контекст:\n" + "\n".join(ctx_parts)})

    # История диалога
    if history:
        for msg in history:
            messages.append(msg)

    # Текущий запрос
    messages.append({"role": "user", "content": user_text})

    return messages